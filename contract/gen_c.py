# sp_config_gen.h / .c
# =================================================================================================
def startup_table(c: C.Contract) -> list[tuple[int, int, int, int, int, str]]:
    """Startup SDO writes as a node-independent table: value = base (+ node id) (+ master id << 16)."""
    master = c["bus"]["master_node_id"]
    seq0 = c.startup_sequence(0)
    seq1 = c.startup_sequence(1)
    c.data["bus"]["master_node_id"] = master + 1
    seq_m = c.startup_sequence(0)
    c.data["bus"]["master_node_id"] = master
    rows = []
    for a, b, m in zip(seq0, seq1, seq_m):
        flags, base = 0, a.value
        if b.value - a.value == 1:
            flags |= 1  # SP_SDO_ADD_NODE
        elif b.value != a.value:
            raise ValueError(f"{a}: value depends on the node id in a way the table can't express")
        if m.value - a.value == 1 << 16:
            flags |= 2  # SP_SDO_ADD_MASTER_HB
            base -= master << 16
        elif m.value != a.value:
            raise ValueError(f"{a}: value depends on the master id in a way the table can't express")
        rows.append((a.index, a.sub, a.size, flags, base & 0xFFFFFFFF, a.note))
    return rows


def config_files(c: C.Contract, g: G.Geometry, pcfg: dict) -> tuple[str, str]:
    cia, hom, cur, prof, csp = c["cia402"], c["homing"], c["current"], c["profile"], c["csp"]
    nodes = c.node_ids
    if len(nodes) > MAX_LEGS:
        raise ValueError("more than 6 drives")
    padded = nodes + [0] * (MAX_LEGS - len(nodes))
    lo, hi = c["actuator"]["soft_limits_mm"]
    ident = c["device"]["identity"]
    m, inp = pcfg["motion"], pcfg["inputs"]
    h = [HEADER, "#ifndef SP_CONFIG_GEN_H\n#define SP_CONFIG_GEN_H\n\n#include <stdint.h>\n\n"]
    d = h.append

    def define(name, value, comment=""):
        d(f"#define {name:<34} {value}{'  /* ' + comment + ' */' if comment else ''}\n")

    d("/* --- versions ------------------------------------------------------------------ */\n")
    define("SP_CONTRACT_VERSION", f'"{c["contract_version"]}"')
    define("SP_GEOMETRY_VERSION", f'"{pcfg["geometry_version"]}"')
    d("\n/* --- bus ----------------------------------------------------------------------- */\n")
    define("SP_MAX_LEGS", MAX_LEGS)
    define("SP_CONTRACT_LEGS", len(nodes), "drives listed in the contract")
    define("SP_DRIVE_NODE_IDS", "{" + ", ".join(map(str, padded)) + "}")
    define("SP_MASTER_NODE_ID", c["bus"]["master_node_id"])
    define("SP_SYNC_PERIOD_MS", c["bus"]["sync"]["period_ms"])
    define("SP_HB_MASTER_PRODUCER_MS", c["heartbeat"]["master_producer_ms"])
    define("SP_HB_DRIVE_PRODUCER_MS", c["heartbeat"]["drive_producer_ms"])
    define("SP_HB_MASTER_CONSUMES_DRIVE_MS", c["heartbeat"]["master_consumes_drive_ms"])
    define("SP_TIMEOUT_BOOTUP_MS", c["timeouts_ms"]["boot_up"])
    define("SP_TIMEOUT_SDO_MS", c["timeouts_ms"]["sdo"])
    define("SP_TIMEOUT_STATE_MS", c["timeouts_ms"]["state_transition"])
    define("SP_IDENTITY_VENDOR", f"0x{ident['vendor_id']:08X}u")
    define("SP_IDENTITY_PRODUCT", f"{ident['product_code']}u")
    define("SP_IDENTITY_MIN_REVISION", f"0x{ident['min_revision']:08X}u")
    drive_rpdo = [p for p in c["pdo"]["rpdo"] if p.get("enabled", True)]
    drive_tpdo = [p for p in c["pdo"]["tpdo"] if p.get("enabled", True)]
    d("/* Master PDOs mirror the drives' PDOs, leg-major: master RPDO k = leg * SP_N_DRIVE_TPDO + j,\n"
      " * master TPDO k = leg * SP_N_DRIVE_RPDO + j (j = position in the lists below). */\n")
    define("SP_N_DRIVE_TPDO", len(drive_tpdo))
    define("SP_N_DRIVE_RPDO", len(drive_rpdo))
    define("SP_DRIVE_TPDO_BASES", "{" + ", ".join(f"0x{p['base']:03X}" for p in drive_tpdo) + "}")
    define("SP_DRIVE_RPDO_BASES", "{" + ", ".join(f"0x{p['base']:03X}" for p in drive_rpdo) + "}")
    for j, p in enumerate(drive_rpdo):
        define(f"SP_MASTER_TPDO_OFFSET_RPDO{p['num']}", j)
    d("\n/* --- units and actuator -------------------------------------------------------- */\n")
    define("SP_COUNTS_PER_MM", c.counts_per_mm)
    define("SP_STROKE_MM", f(c["actuator"]["stroke_mm"]))
    define("SP_SOFT_MIN_MM", f(lo))
    define("SP_SOFT_MAX_MM", f(hi))
    d("\n/* --- currents (2003h), profile, csp --------------------------------------------- */\n")
    define("SP_CURRENT_RUN", cur["run"])
    define("SP_CURRENT_HOMING", cur["homing"])
    define("SP_PROFILE_VELOCITY_MM_S", f(prof["velocity_mm_s"]))
    define("SP_PROFILE_ACCELERATION_MM_S2", f(prof["acceleration_mm_s2"]))
    define("SP_CSP_MAX_VELOCITY_MM_S", f(csp["max_velocity_mm_s"]))
    define("SP_CSP_MAX_ACCELERATION_MM_S2", f(csp["max_acceleration_mm_s2"]))
    d("\n/* --- homing -------------------------------------------------------------------- */\n")
    define("SP_HOMING_METHOD", hom["method"])
    define("SP_HOMING_VELOCITY_MM_S", f(hom["velocity_mm_s"]), "retract (negative direction)")
    define("SP_HOMING_LOAD_POLL_MS", hom["load_poll_ms"])
    define("SP_HOMING_LOAD_STALL", hom["load_stall_threshold"], "2101h <= this = end stop")
    define("SP_HOMING_TIMEOUT_MS", int(hom["timeout_s"] * 1000))
    define("SP_HOMING_PARK_MM", f(hom["park_mm"]))
    d("\n/* --- CiA 402 ------------------------------------------------------------------- */\n")
    for name, v in cia["controlword"].items():
        define(f"SP_CW_{name.upper()}", f"0x{v:04X}u")
    for name, (mask, value) in cia["statusword"].items():
        define(f"SP_SW_{name.upper()}_MASK", f"0x{mask:04X}u")
        define(f"SP_SW_{name.upper()}", f"0x{value:04X}u")
    for name, bit in cia["statusword_bits"].items():
        define(f"SP_SWB_{name.upper()}", f"(1u << {bit})")
    for name, v in cia["modes"].items():
        define(f"SP_MODE_{name.upper()}", v)
    d("\n/* --- startup SDO table (per drive, in PRE-OPERATIONAL, drive in SWITCH ON DISABLED) - */\n")
    define("SP_SDO_ADD_NODE", "0x01u", "value += drive node id")
    define("SP_SDO_ADD_MASTER_HB", "0x02u", "value += master node id << 16")
    d("typedef struct {\n    uint16_t index;\n    uint8_t sub;\n    uint8_t size;\n    uint8_t flags;\n"
      "    uint32_t value;\n} sp_sdo_entry_t;\n")
    rows = startup_table(c)
    define("SP_STARTUP_SDO_COUNT", len(rows))
    d("extern const sp_sdo_entry_t SP_STARTUP_SDO[SP_STARTUP_SDO_COUNT];\n")
    d("\n/* --- EMCY classes -------------------------------------------------------------- */\n")
    d("typedef enum {\n" + "".join(f"    SP_EMCY_{n.upper()},\n" for n in EMCY_CLASSES) + "} sp_emcy_class_t;\n")
    d("typedef struct {\n    uint16_t code;\n    int16_t byte1; /* -1 = any */\n    uint8_t cls;\n} sp_emcy_entry_t;\n")
    define("SP_EMCY_COUNT", len(c["emcy"]))
    d("extern const sp_emcy_entry_t SP_EMCY_TABLE[SP_EMCY_COUNT];\n")
    d("\n/* --- geometry (config/platform.yaml) ------------------------------------------- */\n")
    define("SP_LEG_CLOSED_MM", f(g.closed_length_mm))
    define("SP_NEUTRAL_STROKE_MM", f(g.neutral_stroke_mm))
    define("SP_NEUTRAL_Z_MM", f(g.neutral_z_mm))
    define("SP_WORKSPACE_MARGIN_MM", f(g.margin_mm))
    d("extern const float SP_BASE_JOINTS[6][3];\nextern const float SP_PLATFORM_JOINTS[6][3];\n")
    for k in ("x_mm", "y_mm", "z_mm", "roll_deg", "pitch_deg", "yaw_deg"):
        define(f"SP_LIMIT_{k.upper()}", f(m["limits"][k]))
    define("SP_POSE_MAX_LIN_VEL_MM_S", f(m["max_linear_velocity_mm_s"]))
    define("SP_POSE_MAX_LIN_ACC_MM_S2", f(m["max_linear_acceleration_mm_s2"]))
    define("SP_POSE_MAX_ANG_VEL_DEG_S", f(m["max_angular_velocity_deg_s"]))
    define("SP_POSE_MAX_ANG_ACC_DEG_S2", f(m["max_angular_acceleration_deg_s2"]))
    d("\n/* --- operator inputs ----------------------------------------------------------- */\n")
    js, imu, demo = inp["joystick"], inp["imu"], inp["demo"]
    define("SP_JOY_DEADBAND", f(js["deadband"]))
    define("SP_JOY_EXPO", f(js["expo"]))
    define("SP_JOY_ROLL_DEG", f(js["roll_deg"]))
    define("SP_JOY_PITCH_DEG", f(js["pitch_deg"]))
    define("SP_IMU_GAIN", f(imu["gain"]))
    define("SP_IMU_USE_YAW", int(bool(imu["use_yaw"])))
    define("SP_IMU_CLAMP_DEG", f(imu["clamp_deg"]))
    define("SP_DEMO_IDLE_AFTER_S", f(demo["idle_after_s"]))
    define("SP_DEMO_ROLL_DEG", f(demo["roll_deg"]))
    define("SP_DEMO_PITCH_DEG", f(demo["pitch_deg"]))
    define("SP_DEMO_Z_MM", f(demo["z_mm"]))
    define("SP_DEMO_PERIOD_S", f(demo["period_s"]))
    sup = pcfg.get("supervisor", {})
    d("\n/* --- supervisor ------------------------------------------------------------------ */\n")
    define("SP_AUTO_RECOVER_MS", int(sup.get("auto_recover_after_s", 0) * 1000), "0 = off")
    define("SP_AUTO_RECOVER_MAX_TRIES", int(sup.get("auto_recover_max_tries", 3)))
    d("\n#endif /* SP_CONFIG_GEN_H */\n")

    src = [HEADER, '#include "sp_config_gen.h"\n\n', "const sp_sdo_entry_t SP_STARTUP_SDO[SP_STARTUP_SDO_COUNT] = {\n"]
    for idx, sub, size, flags, value, note in rows:
        src.append(f"    {{0x{idx:04X}, {sub}, {size}, {flags}, 0x{value:08X}u}}, /* {note} */\n")
    src.append("};\n\nconst sp_emcy_entry_t SP_EMCY_TABLE[SP_EMCY_COUNT] = {\n")
    for e in c["emcy"]:
        src.append(f"    {{0x{e['code']:04X}, {e.get('byte1', -1)}, SP_EMCY_{e['class'].upper()}}}, /* {e['text']} */\n")
    src.append("};\n\n")
    for name, joints in (("SP_BASE_JOINTS", g.base), ("SP_PLATFORM_JOINTS", g.platform)):
        src.append(f"const float {name}[6][3] = {{\n")
        for j in joints:
            src.append("    {" + ", ".join(f(v) for v in j) + "},\n")
        src.append("};\n")
    return "".join(h), "".join(src)


# =================================================================================================
# Master object dictionary (CANopenNode v4 OD.h / OD.c)
# =================================================================================================
@dataclass
class Var:
    index: int
    name: str
    ctype: str
    attr: str
    value: int
    group: str = "PERSIST_COMM"


@dataclass
class Arr:
    index: int
    name: str
    ctype: str
    attr0: str
    attr: str
    values: list[int]
    group: str | None = "PERSIST_COMM"  # None: no storage (1003h, served by CO_EM)


@dataclass
class Rec:
    index: int
    name: str
    subs: list[tuple[int, str, str, str, int]]  # sub, field, ctype, attr, value
    group: str = "PERSIST_COMM"
    count_define: str = ""


@dataclass
class OD:
    objects: list = field(default_factory=list)


def mb(attr: str, ctype: str) -> str:
    return attr + (" | ODA_MB" if SIZES[ctype] > 1 else "")


def lit(v: int, ctype: str) -> str:
    if ctype.startswith("int"):
        return str(v)
    return f"0x{v & ((1 << 8 * SIZES[ctype]) - 1):0{2 * SIZES[ctype]}X}"


def master_od(c: C.Contract) -> list:
    nodes = c.node_ids + [0] * (MAX_LEGS - len(c.node_ids))
    hb = c["heartbeat"]
    period_us = c["bus"]["sync"]["period_ms"] * 1000
    rw, r = "ODA_SDO_RW", "ODA_SDO_R"
    objs: list = [
        Var(0x1000, "deviceType", "uint32_t", mb(r, "uint32_t"), 0),
        Var(0x1001, "errorRegister", "uint8_t", "ODA_SDO_R | ODA_TPDO", 0, "RAM"),
        Arr(0x1003, "pre_definedErrorField", "uint32_t", rw, "ODA_SDO_R | ODA_MB", [0] * 8, None),
        Var(0x1005, "COB_ID_SYNCMessage", "uint32_t", mb(rw, "uint32_t"), 0x40000000 | c["bus"]["sync"]["cob_id"]),
        Var(0x1006, "communicationCyclePeriod", "uint32_t", mb(rw, "uint32_t"), period_us),
        Var(0x1007, "synchronousWindowLength", "uint32_t", mb(rw, "uint32_t"), 0),
        Arr(0x1010, "storeParameters", "uint32_t", r, "ODA_SDO_RW | ODA_MB", [1] * 4, "RAM"),
        Arr(0x1011, "restoreDefaultParameters", "uint32_t", r, "ODA_SDO_RW | ODA_MB", [1] * 4, "RAM"),
        Var(0x1012, "COB_IDTimeStampObject", "uint32_t", mb(rw, "uint32_t"), 0x100),
        Var(0x1014, "COB_ID_EMCY", "uint32_t", mb(rw, "uint32_t"), 0x80),
        Var(0x1015, "inhibitTimeEMCY", "uint16_t", mb(rw, "uint16_t"), 0),
        Arr(0x1016, "consumerHeartbeatTime", "uint32_t", r, "ODA_SDO_RW | ODA_MB",
            [(n << 16) | hb["master_consumes_drive_ms"] if n else 0 for n in nodes]),
        Var(0x1017, "producerHeartbeatTime", "uint16_t", mb(rw, "uint16_t"), hb["master_producer_ms"]),
        Rec(0x1018, "identity", [
            (0, "highestSub_indexSupported", "uint8_t", r, 4),
            (1, "vendor_ID", "uint32_t", mb(r, "uint32_t"), 0),
            (2, "productCode", "uint32_t", mb(r, "uint32_t"), 0),
            (3, "revisionNumber", "uint32_t", mb(r, "uint32_t"), 0),
            (4, "serialNumber", "uint32_t", mb(r, "uint32_t"), 0),
        ]),
        Var(0x1019, "synchronousCounterOverflowValue", "uint8_t", rw, 0),
        Rec(0x1200, "SDOServerParameter", [
            (0, "highestSub_indexSupported", "uint8_t", r, 2),
            (1, "COB_IDClientToServerRx", "uint32_t", "ODA_SDO_R | ODA_TPDO | ODA_MB", 0x600),
            (2, "COB_IDServerToClientTx", "uint32_t", "ODA_SDO_R | ODA_TPDO | ODA_MB", 0x580),
        ], "RAM"),
        Rec(0x1280, "SDOClientParameter", [
            (0, "highestSub_indexSupported", "uint8_t", r, 3),
            (1, "COB_IDClientToServerTx", "uint32_t", "ODA_SDO_RW | ODA_TRPDO | ODA_MB", 0x80000000),
            (2, "COB_IDServerToClientRx", "uint32_t", "ODA_SDO_RW | ODA_TRPDO | ODA_MB", 0x80000000),
            (3, "node_IDOfTheSDOServer", "uint8_t", rw, 1),
        ]),
    ]
    # Master RPDOs = the drives' TPDOs; master TPDOs = the drives' RPDOs (same COB-IDs, mirrored mapping).
    drive_tpdo = [p for p in c["pdo"]["tpdo"] if p.get("enabled", True)]
    drive_rpdo = [p for p in c["pdo"]["rpdo"] if p.get("enabled", True)]
    var_of = {  # drive object -> master manufacturer array
        0x6041: 0x2110, 0x6064: 0x2111, 0x6061: 0x2112,
        0x6040: 0x2120, 0x607A: 0x2121, 0x6060: 0x2122, 0x60FF: 0x2123,
    }
    rpdos, tpdos = [], []
    for leg, node in enumerate(nodes):
        for p in drive_tpdo:
            rpdos.append((leg, node, p))
        for p in drive_rpdo:
            tpdos.append((leg, node, p))

    def mapping(leg: int, p: dict) -> list[int]:
        out = []
        for idx, sub in p["map"]:
            size = c.size_signed(idx, sub)[0]
            out.append((var_of[idx] << 16) | ((leg + 1) << 8) | size * 8)
        return out

    for k, (leg, node, p) in enumerate(rpdos):
        cob = (p["base"] + node) if node else 0x80000000 | (p["base"] + leg + 1)
        objs.append(Rec(0x1400 + k, "RPDOCommunicationParameter", [
            (0, "highestSub_indexSupported", "uint8_t", r, 5),
            (1, "COB_IDUsedByRPDO", "uint32_t", mb(rw, "uint32_t"), cob),
            (2, "transmissionType", "uint8_t", rw, 0xFE),  # process on arrival
            (5, "eventTimer", "uint16_t", mb(rw, "uint16_t"), 0),
        ]))
    for k, (leg, node, p) in enumerate(rpdos):
        mp = mapping(leg, p)
        objs.append(Rec(0x1600 + k, "RPDOMappingParameter",
                        [(0, "numberOfMappedApplicationObjectsInPDO", "uint8_t", rw, len(mp))] +
                        [(i + 1, f"applicationObject{i + 1}", "uint32_t", mb(rw, "uint32_t"), mp[i] if i < len(mp) else 0)
                         for i in range(8)]))
    for k, (leg, node, p) in enumerate(tpdos):
        cob = (0x40000000 | (p["base"] + node)) if node else 0xC0000000 | (p["base"] + leg + 1)
        objs.append(Rec(0x1800 + k, "TPDOCommunicationParameter", [
            (0, "highestSub_indexSupported", "uint8_t", r, 6),
            (1, "COB_IDUsedByTPDO", "uint32_t", mb(rw, "uint32_t"), cob),
            (2, "transmissionType", "uint8_t", rw, 0xFE),  # sent on request by the app
            (3, "inhibitTime", "uint16_t", mb(rw, "uint16_t"), 0),
            (5, "eventTimer", "uint16_t", mb(rw, "uint16_t"), 0),
            (6, "SYNCStartValue", "uint8_t", rw, 0),
        ]))
    for k, (leg, node, p) in enumerate(tpdos):
        mp = mapping(leg, p)
        objs.append(Rec(0x1A00 + k, "TPDOMappingParameter",
                        [(0, "numberOfMappedApplicationObjectsInPDO", "uint8_t", rw, len(mp))] +
                        [(i + 1, f"applicationObject{i + 1}", "uint32_t", mb(rw, "uint32_t"), mp[i] if i < len(mp) else 0)
                         for i in range(8)]))
    for idx, name, ctype, pdo in (
        (0x2110, "driveStatusword", "uint16_t", "ODA_RPDO"),
        (0x2111, "drivePositionActual", "int32_t", "ODA_RPDO"),
        (0x2112, "driveModeDisplay", "int8_t", "ODA_RPDO"),
        (0x2120, "driveControlword", "uint16_t", "ODA_TPDO"),
        (0x2121, "driveTargetPosition", "int32_t", "ODA_TPDO"),
        (0x2122, "driveModeOfOperation", "int8_t", "ODA_TPDO"),
        (0x2123, "driveTargetVelocity", "int32_t", "ODA_TPDO"),
    ):
        objs.append(Arr(idx, name, ctype, r, mb(f"ODA_SDO_R | {pdo}", ctype), [0] * MAX_LEGS, "RAM"))
    objs.sort(key=lambda o: o.index)
    return objs, len(rpdos), len(tpdos)


def od_files(c: C.Contract) -> tuple[str, str]:
    objs, n_rpdo, n_tpdo = master_od(c)
    groups = ("PERSIST_COMM", "RAM")
    hdr = [HEADER.replace("*/", "*\n * Master object dictionary for CANopenNode v4 (CANopenEditor layout). */"),
           "#ifndef OD_H\n#define OD_H\n\n"]
    counts = {"NMT": 1, "EM": 1, "SYNC": 1, "SYNC_PROD": 1, "STORAGE": 1, "TIME": 1, "EM_PROD": 1,
              "HB_CONS": 1, "HB_PROD": 1, "SDO_SRV": 1, "SDO_CLI": 1, "RPDO": n_rpdo, "TPDO": n_tpdo}
    for k, v in counts.items():
        hdr.append(f"#define OD_CNT_{k} {v}\n")
    hdr.append("\n")
    for o in objs:
        if isinstance(o, Arr):
            hdr.append(f"#define OD_CNT_ARR_{o.index:04X} {len(o.values)}\n")
    hdr.append("\n")

    def member(o) -> str:
        n = f"x{o.index:04X}_{o.name}"
        if isinstance(o, Var):
            return f"    {o.ctype} {n};\n"
        if isinstance(o, Arr):
            return f"    uint8_t {n}_sub0;\n    {o.ctype} {n}[OD_CNT_ARR_{o.index:04X}];\n"
        return "    struct {\n" + "".join(f"        {ct} {fld};\n" for _, fld, ct, _, _ in o.subs) + f"    }} {n};\n"

    for grp in groups:
        hdr.append("typedef struct {\n" + "".join(member(o) for o in objs if o.group == grp) + f"}} OD_{grp}_t;\n\n")
    for grp in groups:
        hdr.append(f"#ifndef OD_ATTR_{grp}\n#define OD_ATTR_{grp}\n#endif\n"
                   f"extern OD_ATTR_{grp} OD_{grp}_t OD_{grp};\n\n")
    hdr.append("#ifndef OD_ATTR_OD\n#define OD_ATTR_OD\n#endif\nextern OD_ATTR_OD OD_t *OD;\n\n")
    for i, o in enumerate(objs):
        hdr.append(f"#define OD_ENTRY_H{o.index:04X} &OD->list[{i}]\n")
    for i, o in enumerate(objs):
        hdr.append(f"#define OD_ENTRY_H{o.index:04X}_{o.name} &OD->list[{i}]\n")
    hdr.append("\n#endif /* OD_H */\n")

    src = [HEADER, '#define OD_DEFINITION\n#include "301/CO_ODinterface.h"\n#include "OD.h"\n\n'
           "#if CO_VERSION_MAJOR < 4\n#error This Object dictionary is compatible with CANopenNode V4.0 and above!\n#endif\n\n"]

    def init(o) -> str:
        n = f"x{o.index:04X}_{o.name}"
        if isinstance(o, Var):
            return f"    .{n} = {lit(o.value, o.ctype)},\n"
        if isinstance(o, Arr):
            vals = ", ".join(lit(v, o.ctype) for v in o.values)
            return f"    .{n}_sub0 = 0x{len(o.values):02X},\n    .{n} = {{{vals}}},\n"
        body = ",\n".join(f"        .{fld} = {lit(v, ct)}" for _, fld, ct, _, v in o.subs)
        return f"    .{n} = {{\n{body}\n    }},\n"

    for grp in groups:
        src.append(f"OD_ATTR_{grp} OD_{grp}_t OD_{grp} = {{\n" + "".join(init(o) for o in objs if o.group == grp) + "};\n\n")

    def objtype(o) -> str:
        n = f"o_{o.index:04X}_{o.name}"
        if isinstance(o, Var):
            return f"    OD_obj_var_t {n};\n"
        if isinstance(o, Arr):
            return f"    OD_obj_array_t {n};\n"
        return f"    OD_obj_record_t {n}[{len(o.subs)}];\n"

    src.append("typedef struct {\n" + "".join(objtype(o) for o in objs) + "} ODObjs_t;\n\n")
    src.append("static CO_PROGMEM ODObjs_t ODObjs = {\n")
    for o in objs:
        n, x = f"o_{o.index:04X}_{o.name}", f"x{o.index:04X}_{o.name}"
        if isinstance(o, Var):
            src.append(f"    .{n} = {{\n        .dataOrig = &OD_{o.group}.{x},\n        .attribute = {o.attr},\n"
                       f"        .dataLength = {SIZES[o.ctype]}\n    }},\n")
        elif isinstance(o, Arr):
            if o.group is None:
                d0, dd = "NULL", "NULL"
            else:
                d0, dd = f"&OD_{o.group}.{x}_sub0", f"&OD_{o.group}.{x}[0]"
            src.append(f"    .{n} = {{\n        .dataOrig0 = {d0},\n        .dataOrig = {dd},\n"
                       f"        .attribute0 = {o.attr0},\n        .attribute = {o.attr},\n"
                       f"        .dataElementLength = {SIZES[o.ctype]},\n        .dataElementSizeof = sizeof({o.ctype})\n    }},\n")
        else:
            subs = ",\n".join(
                f"        {{\n            .dataOrig = &OD_{o.group}.{x}.{fld},\n            .subIndex = {sub},\n"
                f"            .attribute = {attr},\n            .dataLength = {SIZES[ct]}\n        }}"
                for sub, fld, ct, attr, _ in o.subs)
            src.append(f"    .{n} = {{\n{subs}\n    }},\n")
    src.append("};\n\nstatic OD_ATTR_OD OD_entry_t ODList[] = {\n")
    for o in objs:
        n = f"o_{o.index:04X}_{o.name}"
        if isinstance(o, Var):
            src.append(f"    {{0x{o.index:04X}, 0x01, ODT_VAR, &ODObjs.{n}, NULL}},\n")
        elif isinstance(o, Arr):
            src.append(f"    {{0x{o.index:04X}, 0x{len(o.values) + 1:02X}, ODT_ARR, &ODObjs.{n}, NULL}},\n")
        else:
            src.append(f"    {{0x{o.index:04X}, 0x{len(o.subs):02X}, ODT_REC, &ODObjs.{n}, NULL}},\n")
    src.append("    {0x0000, 0x00, 0, NULL, NULL}\n};\n\nstatic OD_t _OD = {\n"
               "    (sizeof(ODList) / sizeof(ODList[0])) - 1,\n    &ODList[0]\n};\n\nOD_t *OD = &_OD;\n")
    return "".join(hdr), "".join(src)


def generate() -> dict[str, str]:
    c = C.load()
    g = G.load(contract=c)
    h, s = config_files(c, g, G.config())
    odh, odc = od_files(c)
    return {"sp_config_gen.h": h, "sp_config_gen.c": s, "OD.h": odh, "OD.c": odc}


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", type=Path, default=OUT_DIR)
    ap.add_argument("--check", action="store_true", help="fail if the files on disk are out of date")
    args = ap.parse_args()
    files = generate()
    stale = []
    for name, text in files.items():
        path = args.out / name
        if args.check:
            if not path.exists() or path.read_text() != text:
                stale.append(name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    if stale:
        print("out of date (run `make gen`):", ", ".join(stale), file=sys.stderr)
        return 1
    if not args.check:
        print(f"wrote {', '.join(files)} to {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
