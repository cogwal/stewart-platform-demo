"""Generate the C master's configuration from the contract and the platform config.

python -m contract.gen_c [--out master/generated] [--check]

Writes:
  sp_config_gen.h / .c  constants, per-drive startup SDO table, EMCY table, geometry
  OD.h / OD.c           the master's CANopenNode object dictionary (CANopenNode v4 format):
                        SYNC producer, heartbeat consumer for the drives, one SDO client, and the
                        PDOs that mirror the drives' PDOs (12 RPDOs, 18 TPDOs for 6 legs) mapped to
                        manufacturer arrays 2110h..2123h.

The generated files are committed (the ECU build uses them without Python). CI runs --check, which
fails if they are out of date.
"""
from __future__ import annotations

import argparse
import sys
from dataclasses import dataclass, field
from pathlib import Path

import contract as C
from stewart import geometry as G

ROOT = Path(__file__).resolve().parent.parent
OUT_DIR = ROOT / "master" / "generated"
MAX_LEGS = 6
HEADER = ("/* GENERATED by contract/gen_c.py from contract/drive-contract.yaml and config/platform.yaml.\n"
          " * Do not edit: change the YAML and run `make gen`. */\n")

SIZES = {"uint8_t": 1, "int8_t": 1, "uint16_t": 2, "int16_t": 2, "uint32_t": 4, "int32_t": 4}
EMCY_CLASSES = ["info", "warn", "homing_stall", "stall", "stop_all", "stop_all_rehome", "config_error"]


def f(v: float) -> str:
    s = repr(float(v))
    return (s if ("e" in s or "." in s) else s + ".0") + "f"


